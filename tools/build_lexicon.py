#!/usr/bin/env python3
"""
Speurtocht.NL - build the names list and check dictionary coverage.

Usage (from the addon folder):
    python3 tools/build_lexicon.py source/catalog.json

1. Names: every capitalised word in the Dutch text that also appears
   capitalised in the quest's English source (Durnan, Anvilmar, Rockjaw...).
   These are written to Data/Namen.lua. In the reader they can't be saved;
   clicking one turns it red and says it's a name.
2. Coverage: lists every Dutch word that has no meaning in the quest's own
   word list, the dictionaries (Data/Woordenboek*.lua), the names list or the
   fantasy terms (Data/Termen.lua). A batch is finished when this list is empty.
"""
import glob
import json
import os
import re
import sys

STR = r'"((?:[^"\\]|\\.)*)"'
WORD = re.compile(r"[A-Za-zÀ-ÿ][A-Za-zÀ-ÿ'\-]*")
# Sentence-initial Dutch words and interjections that also occur capitalised in English
NOT_NAMES = {"we", "ach", "ah", "ahh", "argh", "grrr", "haha", "hm", "hmm", "a", "o", "is", "in", "hand", "dan", "hier"}


def norm(w):
    return w.strip("'-").lower()


def lua_table_keys(path):
    text = open(path, encoding="utf-8").read()
    return {k.lower(): v for k, v in re.findall(r'\["(.*?)"\]\s*=\s*' + STR, text)}


def load_quests(addon):
    quests = {}
    for path in sorted(glob.glob(os.path.join(addon, "Data", "Start_*.lua")) +
                       glob.glob(os.path.join(addon, "Data", "Dungeon_*.lua")) +
                       glob.glob(os.path.join(addon, "Data", "Attune*.lua")) +
                       glob.glob(os.path.join(addon, "Data", "Quests_*.lua")) +
                       glob.glob(os.path.join(addon, "Data", "Batch_*.lua"))):
        text = open(path, encoding="utf-8").read()
        for m in re.finditer(r"\n\[(\d+)\]\s*=\s*\{(.*?)\n\},", text, re.S):
            qid, body = m.group(1), m.group(2)
            fields = {k: v for k, v in re.findall(r"\b([tdopce])\s*=\s*" + STR, body)}
            glossary = {norm(a): b for a, b in re.findall(r"\{" + STR + r",\s*" + STR + r"\}", body)}
            quests[qid] = (fields, glossary)
    return quests


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    addon = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    source = json.load(open(sys.argv[1], encoding="utf-8"))
    quests = load_quests(addon)

    dictionary, terms = {}, {}
    for path in glob.glob(os.path.join(addon, "Data", "Woordenboek*.lua")):
        dictionary.update(lua_table_keys(path))
    terms_path = os.path.join(addon, "Data", "Termen.lua")
    if os.path.exists(terms_path):
        terms.update(lua_table_keys(terms_path))
    for path in glob.glob(os.path.join(addon, "Data", "Batch_*.lua")):
        text = open(path, encoding="utf-8").read()
        for block, target in (("AddWords", dictionary), ("AddTerms", terms)):
            m = re.search(r"NQ:%s\(\{(.*?)\n\}\)" % block, text, re.S)
            if m:
                target.update({k.lower(): v for k, v in re.findall(r'\["(.*?)"\]\s*=\s*' + STR, m.group(1))})

    names, missing = set(), {}
    for qid, (fields, glossary) in quests.items():
        english = json.dumps(source.get(qid, {}).get("en", {}), ensure_ascii=False)
        for text in fields.values():
            text = re.sub(r"\$[gG][^;]*;|\$[nNcCrRbB]", " ", text)
            for m in WORD.finditer(text):
                w = m.group(0).strip("'-")
                lw = w.lower()
                if (w[0].isupper() and lw not in NOT_NAMES
                        and re.search(r"(?<![\w'])" + re.escape(w) + r"(?![\w])", english)):
                    names.add(lw)
                    if lw.endswith("'s"):
                        names.add(lw[:-2])
    for qid, (fields, glossary) in quests.items():
        for text in fields.values():
            text = re.sub(r"\$[gG][^;]*;|\$[nNcCrRbB]", " ", text)
            for m in WORD.finditer(text):
                lw = norm(m.group(0))
                if lw in names or lw in terms or lw in dictionary or lw in glossary:
                    continue
                missing.setdefault(lw, qid)

    out = os.path.join(addon, "Data", "Namen.lua")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("-- Speurtocht.NL: names of people, places, enemies and items that stay English.\n")
        fh.write("-- Generated by tools/build_lexicon.py - edit NOT_NAMES there, not this file.\n")
        fh.write("local _, NQ = ...\n\nNQ:AddNames({\n")
        line = "   "
        for n in sorted(names):
            item = ' "%s",' % n.replace('"', '\\"')
            if len(line) + len(item) > 110:
                fh.write(line + "\n")
                line = "   "
            line += item
        fh.write(line + "\n})\n")
    print("%d quests, %d names -> %s" % (len(quests), len(names), out))
    if missing:
        print("%d words without a meaning:" % len(missing))
        for w, qid in sorted(missing.items()):
            print("  %-28s (quest %s)" % (w, qid))
    else:
        print("every word has a meaning ✓")


if __name__ == "__main__":
    main()
